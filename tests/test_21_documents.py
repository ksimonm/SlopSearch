# --------------------------------------------------------------------------- helpers


def _uniq(prefix="slopsearch-doc"):
    return f"{prefix}-{uuid.uuid4().hex[:10]}"


def _bulk(client, lines, index=None, params=None, raw=None):
    if raw is None:
        raw = "".join(
            (ln if isinstance(ln, str) else json.dumps(ln, ensure_ascii=False)) + "\n"
            for ln in lines
        )
    path = f"/{index}/_bulk" if index else "/_bulk"
    return client.post(
        path,
        content=raw.encode() if isinstance(raw, str) else raw,
        headers=NDJSON,
        params=params or {},
    )


def _put(client, index, doc_id, doc, **params):
    return client.put(f"/{index}/_doc/{quote(str(doc_id), safe='')}", json=doc, params=params)


def _get(client, index, doc_id, **params):
    return client.get(f"/{index}/_doc/{quote(str(doc_id), safe='')}", params=params)


def _src(client, index, doc_id, **params):
    return client.get(f"/{index}/_source/{quote(str(doc_id), safe='')}", params=params)


def _count(client, index, query=None):
    body = {"query": query} if query else None
    r = client.post(f"/{index}/_count", json=body) if body else client.get(f"/{index}/_count")
    assert r.status_code == 200, r.text
    return r.json()["count"]


def _refresh(client, index):
    assert client.post(f"/{index}/_refresh").status_code == 200


def _err_type(resp):
    return resp.json()["error"]["type"]



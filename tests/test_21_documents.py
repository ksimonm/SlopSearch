    _put(client, idx, "1", {"n": 1})
    if how == "create_endpoint":
        r = client.put(f"/{idx}/_create/1", json={"n": 2})
    else:
        r = _put(client, idx, "1", {"n": 2}, op_type="create")
    assert r.status_code == 409
    err = r.json()["error"]
    assert err["type"] == "version_conflict_engine_exception"
    assert err["reason"] == "[1]: version conflict, document already exists (current version [1])"
    assert err["index"] == idx
    assert r.json()["status"] == 409
    assert err["root_cause"][0]["type"] == "version_conflict_engine_exception"
    assert _src(client, idx, "1").json() == {"n": 1}


